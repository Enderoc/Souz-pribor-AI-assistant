def build_user_message(product: Product, missing_input: list[str], feedback: list[str] | None = None,
                       previous: dict | None = None) -> str:
    payload = json.dumps(product.to_dict(), ensure_ascii=False, indent=2)
    msg = (
        "Входные данные о товаре (JSON). Значение null означает, что данных нет.\n"
        f"<product>\n{payload}\n</product>\n"
    )
    if missing_input:
        msg += "\nСлужебная проверка: во входных данных отсутствуют/пусты поля: " + ", ".join(missing_input) + ".\n"
    msg += "\nСоставь черновик карточки и вызови save_card."
    if feedback:
        msg += (
            "\n\nПредыдущая попытка не прошла автоматическую проверку. Исправь именно эти замечания, "
            "остальное сохрани:\n- " + "\n- ".join(feedback)
        )
        if previous:
            msg += "\n\nПредыдущий вариант:\n" + json.dumps(previous, ensure_ascii=False)
    return msg
